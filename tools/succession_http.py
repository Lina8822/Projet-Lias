from history_support import *
a=accounts();d=login_as('director');team=a['team.id'];before=snapshot('audit_log')
old=db("SELECT id_mandat FROM mandat WHERE id_membre="+a['chef.id']+" AND equipe_id="+team+" AND type_mandat='CHEF_EQUIPE' AND statut='ACTIF' ORDER BY id_mandat DESC LIMIT 1")
check(bool(old),'ancien chef mandat de recette présent')
stable=stable_mandate(old);start=db('SELECT date_debut FROM mandat WHERE id_mandat='+old)
expected=max(datetime.date.fromisoformat(start),datetime.date.fromisoformat(db('SELECT CURRENT_DATE'))-datetime.timedelta(days=1)).isoformat()
new=nominate(d,a['member.id'],'CHEF_EQUIPE',team)
check(db('SELECT statut,date_fin FROM mandat WHERE id_mandat='+old)=='TERMINE\t'+expected,'ancien chef TERMINE avec date fin attendue')
check(stable_mandate(old)==stable,'ancien chef identité équipe et début conservés')
check(new!=old and db('SELECT id_membre,equipe_id,statut FROM mandat WHERE id_mandat='+new)==a['member.id']+'\t'+team+'\tACTIF','nouveau chef mandat distinct lié à même équipe')
check('CHEF_EQUIPE' in login_as('member').req('dashboard')[1],'nouveau rôle chef effectif')
check('MEMBRE_EQUIPE' in login_as('chef').req('dashboard')[1],'ancien chef redevient membre sans effacement')
check(untouched(before,snapshot('audit_log')),'audit antérieur ancien chef et autres comptes strictement inchangé')
restored=nominate(d,a['chef.id'],'CHEF_EQUIPE',team)
check(restored not in [old,new] and db('SELECT COUNT(*) FROM mandat WHERE id_mandat IN ('+old+','+new+','+restored+')')=='3','restauration conserve les trois mandats successifs')
save_results('succession')
